#!/usr/bin/env python3
"""omega_data.py -- data for the neighbor diagrams of eq:total-gauss / eq:omega-weight.

The weight with which a neighbor r + d enters the density variance at r is
    Omega(d) = (l_n^2 / (2 pi d^4)) [2 - e^-X (X^2 + 2X + 2)],   X = 2 d^2 / l_n^2,
l_n = 0.5 um. With g(X) = 2 - e^-X (X^2 + 2X + 2) and d^2d = (pi l_n^2 / 2) dX, the weight
within d is in closed form
    F(d) = 1 - (1 + X) e^-X - g(X)/X ,
so F(infinity) = 1. Near d = 0, g = X^3/3 - X^4/4 + X^5/10 - ..., which avoids the
cancellation in g at small X.

Writes, next to this script (pure python, no numpy):
  omega_curve.dat   d (um), 2 pi d Omega(d) (um^-1), for d = 0..3 um     (neighbor_diagram_v3)
  omega_shade.dat   the same up to the median radius (shaded half)       (neighbor_diagram_v3)
  omega_rings.tex   TikZ disks, gray level proportional to Omega(d)      (neighbor_diagram_v2)
  omega_marks.tex   \\def's of the median radius, the peak, and the fractions
and prints the checks: area 1, median 0.682 um, 93.75% within 2 um, peak of 2 pi d Omega.
"""
import math
import os

LN = 0.5                                   # l_n, um
HERE = os.path.dirname(os.path.abspath(__file__))


def g_of(x):
    if x < 1e-2:
        return x**3 / 3 - x**4 / 4 + x**5 / 10
    return 2 - math.exp(-x) * (x * x + 2 * x + 2)


def omega(d):
    """weight per unit area, um^-2"""
    x = 2 * d * d / LN**2
    if x < 1e-2:
        return 4 * d * d / (3 * math.pi * LN**4) * (1 - 3 * x / 4 + 3 * x * x / 10)
    return LN**2 / (2 * math.pi * d**4) * g_of(x)


def radial(d):
    """weight per unit distance, 2 pi d Omega(d), um^-1"""
    return 2 * math.pi * d * omega(d)


def frac(d):
    """weight within distance d, closed form"""
    x = 2 * d * d / LN**2
    if x < 1e-2:
        return x * x / 6 - x**3 / 12
    return 1 - (1 + x) * math.exp(-x) - g_of(x) / x


def simpson(f, a, b, n=20000):
    h = (b - a) / n
    s = f(a) + f(b)
    for i in range(1, n):
        s += (4 if i % 2 else 2) * f(a + i * h)
    return s * h / 3


def bisect(f, a, b, tol=1e-12):
    fa = f(a)
    for _ in range(200):
        m = 0.5 * (a + b)
        fm = f(m)
        if (fm > 0) == (fa > 0):
            a, fa = m, fm
        else:
            b = m
        if b - a < tol:
            break
    return 0.5 * (a + b)


def argmax(f, a, b, n=200000):
    best, arg = -1.0, a
    for i in range(n + 1):
        d = a + (b - a) * i / n
        v = f(d)
        if v > best:
            best, arg = v, d
    return arg, best


# ------------------------------------------------------------------ checks
# numerical area: Simpson to 50 um, plus the tail l_n^2/(pi d^4) * 2 pi d -> l_n^2 / D^2
D = 50.0
area = simpson(radial, 0.0, D, 200000) + LN**2 / D**2
d_med = bisect(lambda d: frac(d) - 0.5, 0.1, 3.0)
d_pk, v_pk = argmax(radial, 0.0, 3.0)
d_pkO, v_pkO = argmax(omega, 0.0, 3.0)
print(f"area of 2 pi d Omega       = {area:.8f}   (closed form F(inf) = 1)")
print(f"median radius (50% within) = {d_med:.4f} um; Simpson to it: "
      f"{simpson(radial, 0.0, d_med):.6f}")
print(f"within 1 um: {100*frac(1.0):.3f}%,  within 2 um: {100*frac(2.0):.3f}% "
      f"(Simpson {100*simpson(radial, 0.0, 2.0):.3f}%),  within 3 um: {100*frac(3.0):.3f}%")
print(f"Omega(0) = {omega(0.0)},  min Omega on (0,10] = "
      f"{min(omega(0.001 + 9.999 * i / 5000) for i in range(5001)):.3e} (positive)")
print(f"peak of 2 pi d Omega: {v_pk:.4f} um^-1 at d = {d_pk:.4f} um")
print(f"peak of Omega (per area): {v_pkO:.4f} um^-2 at d = {d_pkO:.4f} um")

# ------------------------------------------------------------------ files
with open(os.path.join(HERE, "omega_curve.dat"), "w") as fh:
    fh.write("d rad\n")
    n = 900
    for i in range(n + 1):
        d = 3.0 * i / n
        fh.write(f"{d:.5f} {radial(d):.6f}\n")

with open(os.path.join(HERE, "omega_shade.dat"), "w") as fh:
    fh.write("d rad\n")
    n = 300
    for i in range(n + 1):
        d = d_med * i / n
        fh.write(f"{d:.5f} {radial(d):.6f}\n")

# v2 shading: filled disks from the outside in, each the gray of Omega at its radius, so
# the innermost visible ring at radius d has gray level proportional to Omega(d). Radii in um;
# the picture scales them through its x/y units.
GRAY_MAX = 32          # percent black at the maximum of Omega
R_OUT, DR = 2.3, 0.01
with open(os.path.join(HERE, "omega_rings.tex"), "w") as fh:
    fh.write("% generated by omega_data.py: gray disks, level proportional to Omega(d)\n")
    k = int(round(R_OUT / DR))
    for i in range(k, 0, -1):
        r = i * DR
        # minus the value at R_OUT, so the shading ends without an edge
        lev = max(0.0, GRAY_MAX * (omega(r - DR / 2) - omega(R_OUT)) / v_pkO)
        fh.write(f"\\fill[black!{lev:.2f}] (0,0) circle ({r:.3f});\n")

with open(os.path.join(HERE, "omega_marks.tex"), "w") as fh:
    fh.write("% generated by omega_data.py\n")
    fh.write(f"\\def\\dmed{{{d_med:.4f}}}%  median radius, um\n")
    fh.write(f"\\def\\radmed{{{radial(d_med):.4f}}}%  2 pi d Omega at the median\n")
    fh.write(f"\\def\\dpeak{{{d_pk:.4f}}}%  peak of 2 pi d Omega, um\n")
    fh.write(f"\\def\\radtwo{{{radial(2.0):.4f}}}%  2 pi d Omega at 2 um\n")
print("wrote omega_curve.dat, omega_shade.dat, omega_rings.tex, omega_marks.tex")
